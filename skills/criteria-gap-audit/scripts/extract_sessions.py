#!/usr/bin/env python3
"""Claude Code와 Codex의 로컬 세션 기록에서 사람이 직접 쓴 발화와 AI 응답만 뽑아 한 형식으로 맞춘다.

표준 라이브러리만 쓴다. 출력에는 대화 원문이 들어가므로 공개 저장소 밖에 저장한다.

예:
  python3 extract_sessions.py --out ~/.criteria/audit/sessions.jsonl --sample 20
  python3 extract_sessions.py --stats-only
"""
import argparse
import datetime
import glob
import json
import os
import random
import re
import sys
from collections import Counter, OrderedDict

# 도구가 사용자 발화 자리에 끼워 넣는 텍스트. 이 태그로 시작하면 사람이 쓴 말이 아니다.
INJECTED_TAGS = (
    "command-name", "command-message", "command-args",
    "local-command-stdout", "local-command-stderr", "local-command-caveat",
    "task-notification", "system-reminder", "bash-input", "bash-stdout", "bash-stderr",
    "environment_context", "user_instructions", "turn_aborted", "user_shell_command",
)
INJECTED_PREFIXES = (
    "[Request interrupted",
    "Caveat: The messages below were generated by the user while running local commands",
    "# AGENTS.md instructions",
    "This session is being continued from a previous conversation",
)
# 사람이 쓴 발화 안에 섞여 들어오는 맥락 블록. 통째로 지운다.
STRIP_BLOCKS = ("system-reminder", "ide_selection", "ide_opened_file", "ide_diagnostics")
PASTE_KEEP = 300


def clean_user_text(text):
    """사람이 쓴 부분만 남긴다. 사람이 쓴 말이 아니면 빈 문자열."""
    if not isinstance(text, str):
        return ""
    t = text.strip()
    if not t:
        return ""
    m = re.match(r"<([A-Za-z_-]+)", t)
    if m and m.group(1) in INJECTED_TAGS:
        return ""
    if t.startswith(INJECTED_PREFIXES):
        return ""
    for tag in STRIP_BLOCKS:
        t = re.sub(r"<%s\b[^>]*>.*?</%s>" % (tag, tag), "", t, flags=re.S)

    def paste(mt):
        body = mt.group(1).strip()
        more = " ...(+%d자)" % (len(body) - PASTE_KEEP) if len(body) > PASTE_KEEP else ""
        return "[붙여넣은 내용] " + body[:PASTE_KEEP] + more

    # 닫는 태그에도 id가 붙을 수 있고(</pasted_content id="..">), 닫는 태그가 없을 수도 있다.
    t = re.sub(r"<pasted_content\b[^>]*>(.*?)(?:</pasted_content\b[^>]*>|\Z)", paste, t, flags=re.S)
    return t.strip()


def clip(text, limit):
    if limit and len(text) > limit:
        return text[:limit] + " ...(+%d자 생략)" % (len(text) - limit)
    return text


def project_label(cwd):
    """경로 대신 폴더 이름만 쓴다. 작업 트리(worktree)는 원래 저장소 이름으로 묶는다."""
    if not cwd:
        return "(unknown)"
    for marker in ("/.claude/worktrees/", "/.codex/worktrees/", "/.worktrees/"):
        if marker in cwd:
            cwd = cwd.split(marker)[0]
    return os.path.basename(cwd.rstrip("/")) or "(root)"


def add_turn(turns, role, text, ts):
    """같은 역할이 이어지면 한 턴으로 합친다. 같은 사용자 발화가 두 번 기록되면 하나만 남긴다."""
    if not text:
        return
    if turns and turns[-1]["role"] == role:
        if role == "user" and turns[-1]["text"] == text:
            return
        turns[-1]["text"] += "\n\n" + text
        return
    turns.append({"role": role, "text": text, "ts": ts})


def read_jsonl(path, stats):
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    yield json.loads(line)
                except ValueError:
                    stats["줄 해석 실패"] += 1
    except OSError:
        stats["파일 읽기 실패"] += 1


# ---------- Claude Code ----------

def claude_files(root):
    # 최상위 <프로젝트>/<세션>.jsonl만 본다. <세션>/subagents/ 아래는 서브에이전트 기록이다.
    return sorted(glob.glob(os.path.join(root, "*", "*.jsonl")))


def parse_claude(path, max_chars, stats):
    turns, cwd, sid, first_ts = [], None, None, None
    for o in read_jsonl(path, stats):
        typ = o.get("type")
        if typ not in ("user", "assistant"):
            continue
        if o.get("isSidechain"):
            continue
        cwd = cwd or o.get("cwd")
        sid = sid or o.get("sessionId")
        ts = o.get("timestamp")
        first_ts = first_ts or ts
        content = (o.get("message") or {}).get("content")
        if typ == "user":
            if o.get("isMeta") or o.get("isCompactSummary"):
                continue
            origin = o.get("origin")
            if isinstance(origin, dict) and origin.get("kind") not in (None, "human"):
                continue
            if isinstance(content, str):
                parts = [content]
            else:
                parts = [b.get("text", "") for b in (content or []) if isinstance(b, dict) and b.get("type") == "text"]
            text = "\n".join(p for p in (clean_user_text(x) for x in parts) if p)
            add_turn(turns, "user", clip(text, max_chars), ts)
        else:
            parts = [b.get("text", "") for b in (content or []) if isinstance(b, dict) and b.get("type") == "text"]
            text = "\n".join(p.strip() for p in parts if p and p.strip())
            add_turn(turns, "assistant", text, ts)
    for t in turns:
        if t["role"] == "assistant":
            t["text"] = clip(t["text"], max_chars)
    sid = sid or os.path.splitext(os.path.basename(path))[0]
    return {"tool": "claude", "id": sid, "project": project_label(cwd), "started_at": first_ts, "turns": turns}


# ---------- Codex ----------

def codex_files(root):
    files = glob.glob(os.path.join(root, "sessions", "**", "*.jsonl"), recursive=True)
    files += glob.glob(os.path.join(root, "archived_sessions", "*.jsonl"))
    return sorted(set(files))


def codex_imported_ids(root):
    """Codex가 다른 도구(Claude Code 등)에서 가져온 세션 id. 원본과 중복이므로 뺀다."""
    path = os.path.join(root, "external_agent_session_imports.json")
    try:
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
    except (OSError, ValueError):
        return set()
    recs = data.get("records", []) if isinstance(data, dict) else []
    return {r.get("imported_thread_id") for r in recs if isinstance(r, dict) and r.get("imported_thread_id")}


def parse_codex(path, max_chars, stats):
    meta = None
    typed, fallback, assistant_events = [], [], []
    seq = 0
    for o in read_jsonl(path, stats):
        seq += 1
        typ = o.get("type")
        p = o.get("payload") or {}
        ts = o.get("timestamp")
        if typ == "session_meta" and meta is None:
            meta = p
        elif typ == "event_msg" and p.get("type") == "user_message":
            typed.append((seq, ts, p.get("message", "")))
        elif typ == "event_msg" and p.get("type") == "item_completed" and (p.get("item") or {}).get("type") == "UserMessage":
            blocks = (p.get("item") or {}).get("content") or []
            text = "\n".join((b.get("text") or "") for b in blocks if isinstance(b, dict))
            typed.append((seq, ts, text))
        elif typ == "response_item" and p.get("type") == "message":
            blocks = p.get("content") or []
            if p.get("role") == "user":
                text = "\n".join(b.get("text", "") for b in blocks if isinstance(b, dict) and b.get("type") == "input_text")
                fallback.append((seq, ts, text))
            elif p.get("role") == "assistant":
                text = "\n".join(b.get("text", "") for b in blocks if isinstance(b, dict) and b.get("type") == "output_text")
                assistant_events.append((seq, ts, text.strip()))
    # 사람이 입력한 발화는 이벤트 쪽에 따로 남는다. 이벤트가 없는 옛 형식일 때만 모델 입력에서 고른다.
    user_events = typed if typed else fallback
    events = [(s, ts, "user", clean_user_text(t)) for s, ts, t in user_events]
    events += [(s, ts, "assistant", t) for s, ts, t in assistant_events]
    events.sort(key=lambda e: e[0])
    turns = []
    for _, ts, role, text in events:
        add_turn(turns, role, text, ts)
    for t in turns:
        t["text"] = clip(t["text"], max_chars)
    meta = meta or {}
    return {
        "tool": "codex",
        "id": meta.get("id") or os.path.splitext(os.path.basename(path))[0],
        "project": project_label(meta.get("cwd")),
        "started_at": meta.get("timestamp") or (turns[0]["ts"] if turns else None),
        "turns": turns,
        "_subagent": isinstance(meta.get("source"), dict) and "subagent" in meta.get("source"),
    }


# ---------- 모으기, 거르기, 표본 ----------

def parse_date(value):
    if not value:
        return None
    try:
        return datetime.datetime.fromisoformat(str(value).replace("Z", "+00:00")).date()
    except ValueError:
        return None


def collect(args, stats):
    sessions = []
    tools = set(args.tools.split(","))
    if "claude" in tools:
        for path in claude_files(os.path.expanduser(args.claude_dir)):
            stats["claude 파일"] += 1
            sessions.append(parse_claude(path, args.max_chars, stats))
    if "codex" in tools:
        root = os.path.expanduser(args.codex_dir)
        imported = codex_imported_ids(root) if "claude" in tools else set()
        seen = set()
        for path in codex_files(root):
            stats["codex 파일"] += 1
            s = parse_codex(path, args.max_chars, stats)
            if s.pop("_subagent"):
                stats["제외: 서브에이전트"] += 1
                continue
            if s["id"] in imported:
                stats["제외: 다른 도구에서 가져온 사본"] += 1
                continue
            if s["id"] in seen:
                stats["제외: 같은 세션 중복 파일"] += 1
                continue
            seen.add(s["id"])
            sessions.append(s)

    since = parse_date(args.since) if args.since else None
    kept = []
    for s in sessions:
        s["user_turns"] = sum(1 for t in s["turns"] if t["role"] == "user")
        if s["user_turns"] < args.min_user_turns:
            stats["제외: 사용자 발화 %d개 미만" % args.min_user_turns] += 1
            continue
        if since and (parse_date(s["started_at"]) or datetime.date.min) < since:
            stats["제외: 기간 밖"] += 1
            continue
        kept.append(s)
    return kept


def sample(sessions, n, seed):
    """(도구, 프로젝트) 묶음을 돌아가며 하나씩 뽑는다. 한 프로젝트에 기록이 몰려 있어도 고르게 섞인다."""
    if not n or n >= len(sessions):
        return list(sessions)
    rng = random.Random(seed)
    groups = OrderedDict()
    for s in sorted(sessions, key=lambda s: (s["tool"], s["project"], s["id"])):
        groups.setdefault((s["tool"], s["project"]), []).append(s)
    queues = list(groups.values())
    for q in queues:
        rng.shuffle(q)
    rng.shuffle(queues)
    picked = []
    while len(picked) < n:
        for q in queues:
            if q and len(picked) < n:
                picked.append(q.pop())
        queues = [q for q in queues if q]
    return picked


def summary(stats, kept, picked):
    lines = ["[추출 요약]"]
    lines += ["  %s: %d" % (k, v) for k, v in stats.items()]
    lines.append("  남은 세션: %d" % len(kept))
    by = Counter((s["tool"], s["project"]) for s in kept)
    lines.append("  도구·프로젝트 묶음: %d개" % len(by))
    for (tool, proj), c in by.most_common(10):
        lines.append("    %s / %s: %d" % (tool, proj, c))
    if len(by) > 10:
        lines.append("    ... 외 %d개 묶음" % (len(by) - 10))
    if picked is not None and len(picked) != len(kept):
        pb = Counter((s["tool"], s["project"]) for s in picked)
        lines.append("  표본: %d개 (묶음 %d개에서)" % (len(picked), len(pb)))
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--claude-dir", default="~/.claude/projects")
    ap.add_argument("--codex-dir", default="~/.codex")
    ap.add_argument("--tools", default="claude,codex", help="claude, codex 중 쉼표로")
    ap.add_argument("--since", help="YYYY-MM-DD 이후 시작한 세션만")
    ap.add_argument("--min-user-turns", type=int, default=3, help="사용자 발화가 이보다 적은 세션은 뺀다")
    ap.add_argument("--sample", type=int, default=0, help="표본 크기. 0이면 전부")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--max-chars", type=int, default=1500, help="턴 하나에 남길 최대 글자 수")
    ap.add_argument("--out", help="출력 JSONL 경로. 공개 저장소 밖에 둔다")
    ap.add_argument("--stats-only", action="store_true", help="요약만 출력하고 아무것도 쓰지 않는다")
    args = ap.parse_args(argv)

    stats = Counter()
    kept = collect(args, stats)
    picked = sample(kept, args.sample, args.seed)
    print(summary(stats, kept, picked), file=sys.stderr)
    if args.stats_only:
        return 0
    if not args.out:
        print("--out 경로가 필요하다 (또는 --stats-only).", file=sys.stderr)
        return 2
    out = os.path.expanduser(args.out)
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        for s in picked:
            f.write(json.dumps(s, ensure_ascii=False) + "\n")
    print("저장: %s (%d개 세션)" % (out, len(picked)), file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
